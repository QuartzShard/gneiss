//! Handlers for firmware events.
//!
//! A service is a stream of events from the firmware, such as the time ticking over or the
//! battery level changing. Mark a free function with
//! [`#[gneiss::service]`](macro@crate::service), naming the service and anything it takes, and
//! gneiss subscribes it once your `main` has returned:
//!
//! ```no_run,standalone_crate
//! # use gneiss::{service::*, time};
//! # gneiss::__doctest_slices!();
//! #[gneiss::service(TickService, time::TimeUnits::MINUTES)]
//! fn on_minute(_time: time::TickTime, _changed: time::TimeUnits) {
//!     // ...
//! }
//! ```
//!
//! The function's signature is the service's [`Service::Handler`]. Anything after the service's
//! name becomes its [`Service::SubscribeArg`]: list the values separated by commas, and the macro
//! passes several as a tuple. Each service can be subscribed once per app; a second
//! `#[gneiss::service]` for the same one is a link error.
//!
//! Handlers run on the app's single task, between other callbacks, so they never race the UI. To
//! change what's on screen, take a [`UiGuard`](crate::ui::UiGuard) with `UiGuard::enter()` and reach
//! the window through its [`StaticWindow`](crate::ui::StaticWindow).
//!
//! # Context
//!
//! [`TouchService`], [`HealthService`] and [`AppMessageService`] can carry state between calls. Pass
//! `Some(value)` as the context argument and the handler gets `Some(&mut value)` every time; the
//! value is moved to the app heap for the rest of the app's life. Pass `None` to go without.
//!
//! # Reading on demand
//!
//! [`Peekable`] services can also be read without waiting for an event: `BatteryService::peek(())`
//! is the current charge state.
//!
//! # Subscribing at runtime
//!
//! With `enabled_at_boot = false` the function is registered but not subscribed. Any registered
//! function can be subscribed again with [`Subscribe::subscribe`], from anywhere, and most can be
//! stopped with [`Unsubscribe::unsubscribe`]:
//!
//! ```no_run,standalone_crate
//! # use gneiss::{service::*, time};
//! # gneiss::__doctest_slices!();
//! #[gneiss::service(TickService, enabled_at_boot = false, time::TimeUnits::MINUTES)]
//! fn on_tick(_time: time::TickTime, _changed: time::TimeUnits) {}
//!
//! fn faster() {
//!     TickService::subscribe(time::TimeUnits::SECONDS);
//! }
//! ```
//!
//! Subscribing a service with no registered function is a link error. A context service keeps the
//! context from its first subscription.
//!
//! # Availability
//!
//! A service only exists on watches with the hardware behind it: [`CompassService`] with
//! `cfg(pbl_compass)`, [`HealthService`] with `cfg(pbl_health)` and [`TouchService`] with
//! `cfg(pbl_touch)`.
